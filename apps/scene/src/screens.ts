let cachedText = '';
let cachedCols: number[] = [];
/** Text as a strip of 7-bit columns, with a screen's width of blank lead-in so it scrolls in. */
export function textColumns(text: string): number[] {
  if (text === cachedText) return cachedCols;
  const cols: number[] = new Array(9).fill(0);
  for (const ch of text.toUpperCase()) {
    const g = FONT[ch] ?? FONT['?'];
    cols.push(...g, 0);
  }
  cachedText = text;
  cachedCols = cols;
  return cols;
}
